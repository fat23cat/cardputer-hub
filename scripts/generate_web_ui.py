#!/usr/bin/env python3
"""Compile the WEB ACCESS page and its icons into the firmware (plan 050).

web/index.html is gzipped; the home-screen icons are drawn here as PNGs (a
pixel "HUB" in the Cardputer palette); the web app manifest names them. All of
it becomes src/services/web_access/web_ui_asset.h.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import pathlib
import re
import struct
import sys
import zlib
from collections.abc import Sequence

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / "web" / "index.html"
OUTPUT = ROOT / "src" / "services" / "web_access" / "web_ui_asset.h"
BYTES_PER_LINE = 16

INK = (0x17, 0x15, 0x0F)
BONE = (0xF4, 0xF2, 0xEC)
LEAF = (0x4C, 0xB9, 0x49)

# 5x7 cells, like the Cardputer's own bitmap labels.
GLYPHS = {
    "H": ["#...#", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"],
    "U": ["#...#", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."],
    "B": ["####.", "#...#", "#...#", "####.", "#...#", "#...#", "####."],
}
# The word, one blank column between letters, then a Leaf status square.
WORD_COLUMNS = 3 * 5 + 2 + 1 + 2
WORD_ROWS = 7

ICON_SIZES = {"apple-touch-icon.png": 180, "icon-192.png": 192, "icon-512.png": 512}

MANIFEST = {
    "name": "Cardputer Hub",
    "short_name": "Hub",
    "start_url": "/",
    "scope": "/",
    "display": "standalone",
    "background_color": "#F4F2EC",
    "theme_color": "#F4F2EC",
    "icons": [
        {"src": "/icon-192.png", "sizes": "192x192", "type": "image/png"},
        {"src": "/icon-512.png", "sizes": "512x512", "type": "image/png"},
    ],
}


def icon_pixels(size: int) -> list[list[tuple[int, int, int]]]:
    cell = max(1, int(size * 0.8) // WORD_COLUMNS)
    left = (size - WORD_COLUMNS * cell) // 2
    top = (size - WORD_ROWS * cell) // 2
    cells: dict[tuple[int, int], tuple[int, int, int]] = {}
    column = 0
    for letter in "HUB":
        for row, line in enumerate(GLYPHS[letter]):
            for offset, mark in enumerate(line):
                if mark == "#":
                    cells[(column + offset, row)] = BONE
        column += 6
    # A 2x2 square level with the top of the letters, like Home's status dot.
    for dx in (0, 1):
        for dy in (0, 1):
            cells[(column + dx, dy)] = LEAF
    pixels = []
    for y in range(size):
        row = []
        for x in range(size):
            cx, cy = (x - left), (y - top)
            colour = INK
            if cx >= 0 and cy >= 0:
                colour = cells.get((cx // cell, cy // cell), INK)
            row.append(colour)
        pixels.append(row)
    return pixels


def png(pixels: list[list[tuple[int, int, int]]]) -> bytes:
    height = len(pixels)
    width = len(pixels[0])
    raw = b"".join(b"\x00" + bytes(channel for pixel in row for channel in pixel) for row in pixels)

    def chunk(kind: bytes, data: bytes) -> bytes:
        return (
            struct.pack(">I", len(data))
            + kind
            + data
            + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)
        )

    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", header)
        + chunk(b"IDAT", zlib.compress(raw, 9))
        + chunk(b"IEND", b"")
    )


def files(page: bytes) -> list[tuple[str, str, str, bool, bytes]]:
    """(C++ name, served path, content type, gzip-encoded, bytes)."""
    # mtime=0 keeps the output independent of when it was generated.
    result = [("Page", "/", "text/html; charset=utf-8", True, gzip.compress(page, 9, mtime=0))]
    for name, size in ICON_SIZES.items():
        identifier = "".join(part.capitalize() for part in name[:-4].replace("-", " ").split())
        result.append((identifier, "/" + name, "image/png", False, png(icon_pixels(size))))
    manifest = json.dumps(MANIFEST, separators=(",", ":")).encode()
    result.append(("Manifest", "/manifest.webmanifest", "application/manifest+json", False, manifest))
    return result


def render(page: bytes) -> str:
    lines = [
        "#pragma once",
        "",
        "// Generated by scripts/generate_web_ui.py from web/index.html. Do not edit;",
        "// change the page or the script and run the script.",
        "",
        "#include <array>",
        "#include <string_view>",
        "",
        "// clang-format off",
        "namespace cardputer_hub::services {",
        "",
    ]
    entries = files(page)
    for identifier, path, _, encoded, data in entries:
        note = f"{len(page)} bytes of HTML, gzip-compressed" if encoded else f"{len(data)} bytes"
        lines.append(f"// {path}: {note}.")
        lines.append(f"inline constexpr unsigned char webUi{identifier}Data[] = {{")
        for start in range(0, len(data), BYTES_PER_LINE):
            chunk = data[start : start + BYTES_PER_LINE]
            lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
        lines += ["};", ""]
    lines += [
        "struct WebUiFile {",
        "    std::string_view path;",
        "    std::string_view contentType;",
        "    // Sent with Content-Encoding: gzip.",
        "    bool gzip;",
        "    std::string_view body;",
        "};",
        "",
        "[[nodiscard]] inline std::string_view webUiBytes(const unsigned char* data,",
        "                                                std::size_t size) {",
        "    return {reinterpret_cast<const char*>(data), size};",
        "}",
        "",
        f"[[nodiscard]] inline const std::array<WebUiFile, {len(entries)}>& webUiFiles() {{",
        f"    static const std::array<WebUiFile, {len(entries)}> files = {{{{",
    ]
    for identifier, path, content_type, encoded, _ in entries:
        data = f"webUi{identifier}Data"
        lines.append(
            f'        {{"{path}", "{content_type}", {"true" if encoded else "false"}, '
            f"webUiBytes({data}, sizeof({data}))}},"
        )
    lines += [
        "    }};",
        "    return files;",
        "}",
        "",
        "// The file served at `path`, or nullptr.",
        "[[nodiscard]] inline const WebUiFile* webUiFile(std::string_view path) {",
        "    for (const auto& file : webUiFiles()) {",
        "        if (file.path == path)",
        "            return &file;",
        "    }",
        "    return nullptr;",
        "}",
        "",
        "} // namespace cardputer_hub::services",
        "// clang-format on",
        "",
    ]
    return "\n".join(lines)


ARRAY = re.compile(r"inline constexpr unsigned char webUi(\w+)Data\[\] = \{(.*?)\};", re.S)
SIZE_NOTE = re.compile(r"^// /\S*: .*$\n", re.M)
PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"


def png_content(data: bytes) -> bytes:
    """IHDR and the inflated image data: what a PNG shows, not how it was compressed."""
    position, header, image = len(PNG_SIGNATURE), b"", b""
    while position < len(data):
        (length,) = struct.unpack(">I", data[position : position + 4])
        kind = data[position + 4 : position + 8]
        body = data[position + 8 : position + 8 + length]
        if kind == b"IHDR":
            header = body
        elif kind == b"IDAT":
            image += body
        position += 12 + length
    return header + zlib.decompress(image)


def canonical(header: str) -> str:
    """The header with each array replaced by a digest of its decoded content.

    zlib builds differ between platforms, so the same page and icons can
    compress to different bytes; the check compares what they contain.
    """

    def decode(match: re.Match[str]) -> str:
        name, body = match.group(1), match.group(2)
        data = bytes(int(value, 16) for value in re.findall(r"0x([0-9a-f]{2})", body))
        if name == "Page":
            data = gzip.decompress(data)
        elif data.startswith(PNG_SIGNATURE):
            data = png_content(data)
        return f"{name}: {hashlib.sha256(data).hexdigest()}"

    return SIZE_NOTE.sub("", ARRAY.sub(decode, header))


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail when the generated header is out of date"
    )
    arguments = parser.parse_args(argv)
    expected = render(SOURCE.read_bytes())
    if arguments.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if canonical(current) != canonical(expected):
            print(f"{OUTPUT.relative_to(ROOT)} is out of date; run {__file__}", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
